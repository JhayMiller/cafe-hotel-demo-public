import assert from 'node:assert/strict';
import {advanceFlight,createFlight,replayFlight} from '../src/lib/game-engine.js';
import {applyRecordBonus,earnedReward,earnsRecordBonus} from '../src/lib/game-rewards.js';
import {gameAllowance} from '../src/lib/game-access.js';
import {createRewardPin,hashRewardPin,maskPhone,validRewardPin} from '../src/lib/reward-verification.js';

const client=createFlight(123456),flapTicks:number[]=[];
while(!client.finished&&client.tick<36000){
  const next=client.obstacles.find(obstacle=>obstacle.x+58>=58),target=next?.gapY??285;
  const flap=client.y>target+20&&client.vy>0;
  if(flap)flapTicks.push(client.tick+1);
  advanceFlight(client,flap);
}
assert.ok(client.score>=21,'la simulación de regresión debe superar los 21 puntos del caso reportado');
const first=replayFlight(123456,flapTicks,client.tick),second=replayFlight(123456,flapTicks,client.tick);
assert.deepEqual(first,second,'la reconstrucción debe ser determinista');
assert.equal(first.score,client.score,'teléfono y servidor deben conservar exactamente el mismo puntaje');
assert.equal(first.terminalTick,client.tick,'teléfono y servidor deben terminar en el mismo tick');
assert.equal(first.finishReason,client.finishReason,'teléfono y servidor deben registrar el mismo final');
const displaced=replayFlight(123456,flapTicks.map(tick=>tick+1),client.tick);
assert.notDeepEqual(displaced,first,'mover los impulsos un tick debe producir evidencia distinta y nunca ajustarse silenciosamente');
const wingContact=createFlight(7);wingContact.nextSpawnTick=999;wingContact.obstacles=[{x:82,gapY:347.3,passed:false}];advanceFlight(wingContact);
assert.equal(wingContact.finished,false,'las alas pueden tocar una palma cuando el tronco y la cabeza siguen dentro del espacio');
const bodyContact=createFlight(7);bodyContact.nextSpawnTick=999;bodyContact.obstacles=[{x:82,gapY:357.3,passed:false}];advanceFlight(bodyContact);
assert.equal(bodyContact.finishReason,'obstacle','el contacto del tronco o la cabeza sí debe terminar el vuelo');
assert.equal(earnedReward('individual',9,1),null,'no debe premiar menos de 10 puntos');
assert.equal(earnedReward('individual',10,1)?.discountPercent,2,'10 puntos individuales entregan 2%');
assert.equal(earnedReward('individual',30,1)?.discountPercent,10,'30 puntos individuales se limitan a 10%');
assert.equal(earnedReward('friends',36,4),null,'el promedio de mesa menor de 10 no debe premiar');
assert.equal(earnedReward('friends',40,4)?.discountPercent,2,'el promedio de 10 habilita 2% para la mesa');
assert.equal(earnedReward('friends',120,4)?.discountPercent,6,'el promedio de 30 se limita a 6% para la mesa');
assert.equal(earnsRecordBonus(9,12),false,'un récord previo menor de 10 no habilita bono');
assert.equal(earnsRecordBonus(10,11),true,'superar un récord base de 10 habilita bono');
assert.equal(applyRecordBonus(earnedReward('individual',25,1),true)?.discountPercent,9,'el récord agrega un punto porcentual');
assert.equal(applyRecordBonus(earnedReward('individual',30,1),true)?.discountPercent,10,'el récord nunca supera 10%');
const now=new Date('2026-10-25T12:00:00.000Z');
assert.equal(gameAllowance(0,null,now).gamesRemaining,3,'un pedido nuevo habilita tres partidas');
assert.equal(gameAllowance(2,new Date('2026-10-25T11:00:00.000Z'),now).gamesRemaining,1,'la tercera partida debe seguir disponible');
assert.equal(gameAllowance(3,new Date('2026-10-25T11:00:00.000Z'),now).canStart,false,'la cuarta partida debe esperar seis horas');
assert.equal(gameAllowance(3,new Date('2026-10-25T05:59:59.000Z'),now).gamesRemaining,3,'el ciclo debe reabrirse después de seis horas');
assert.equal(gameAllowance(4,new Date('2026-10-25T11:00:00.000Z'),now).gamesRemaining,2,'el ciclo nuevo debe volver a contar desde uno');
process.env.PIN_PEPPER='p'.repeat(32);
const rewardPin=createRewardPin(),challengeId='00000000-0000-4000-8000-000000000001',rewardId='00000000-0000-4000-8000-000000000002';
assert.match(rewardPin,/^\d{6}$/,'el PIN debe tener seis dígitos');
const rewardHash=hashRewardPin(challengeId,rewardId,rewardPin);
assert.equal(validRewardPin(challengeId,rewardId,rewardPin,rewardHash),true,'el PIN correcto debe verificarse');
assert.equal(validRewardPin(challengeId,rewardId,'999999',rewardHash),rewardPin==='999999','un PIN distinto debe rechazarse');
assert.equal(maskPhone('+573205263602'),'+57 ••• ••• 02','el teléfono debe mostrarse enmascarado');
console.log('Motor y umbrales del juego verificados.');
